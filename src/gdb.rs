//! Run gdb in batch mode against a core file and parse the backtrace.
//!
//! We shell out rather than link against libgdb: it is the only sensible way to
//! get symbolication that works across every language gdb can already handle,
//! and it lets debuginfod do the source-line resolution transparently when
//! `DEBUGINFOD_URLS` is set.

use anyhow::{anyhow, Context, Result};
use std::path::Path;
use std::process::Command;

pub struct RawFrame {
    pub index: u32,
    pub address: Option<String>,
    pub function: Option<String>,
    pub file: Option<String>,
    pub line: Option<u32>,
    /// Loaded object (executable or shared library) the frame is in. Filled
    /// from `bt`'s `from /path/to/lib` clause when there's no symbol, or
    /// otherwise resolved from the frame's address against `info
    /// sharedlibrary`.
    pub binary: Option<String>,
}

/// One row from `info sharedlibrary`: an address range and the loaded path.
struct Shlib {
    from: u64,
    to: u64,
    path: String,
}

/// Path to the executable that produced `core`, extracted from `file` output.
/// gdb prints `Core was generated by '/usr/bin/foo arg'.` when it can read the
/// NT_FILE / auxv notes, which is what we care about.
pub struct GdbInfo {
    pub executable: Option<String>,
    pub command_line: Option<String>,
    pub signal: Option<i32>,
    pub signal_name: Option<String>,
    pub frames: Vec<RawFrame>,
}

pub fn analyze(core: &Path, executable: Option<&Path>) -> Result<GdbInfo> {
    let mut cmd = Command::new("gdb");
    cmd.arg("--batch")
        .arg("--quiet")
        .arg("-nx")
        .arg("-iex")
        .arg("set pagination off")
        .arg("-iex")
        .arg("set print frame-arguments none")
        .arg("-iex")
        .arg("set print frame-info source-and-location")
        // Enable debuginfod without prompting so source lines resolve when the
        // debug package isn't installed locally.
        .arg("-iex")
        .arg("set debuginfod enabled on")
        // `bt` on its own only tells us which shared object each frame is in
        // when it lacks a symbol ("from /usr/lib/foo"). We want that for
        // every frame so we can attribute the frame to a dpkg package, even
        // when debuginfod supplied a source line -- so also dump the load
        // ranges of every shared library and let the caller pin each frame's
        // address to one of them (addresses outside every shlib range are
        // taken to be in the executable itself).
        .arg("-ex")
        .arg("info sharedlibrary")
        .arg("-ex")
        .arg("bt");
    if let Some(exe) = executable {
        cmd.arg(exe);
    }
    cmd.arg("--core").arg(core);

    let output = cmd
        .output()
        .context("failed to spawn gdb; is it installed?")?;
    let text = String::from_utf8_lossy(&output.stdout);
    let err_text = String::from_utf8_lossy(&output.stderr);
    let info = parse(&text, &err_text);
    // gdb often exits non-zero on damaged cores but still prints a usable
    // backtrace, and can equally exit 0 with nothing useful. Judge success on
    // whether we actually got any signal we can carry through to the report.
    if info.frames.is_empty() && info.executable.is_none() {
        return Err(anyhow!(
            "gdb produced no usable output (exit {}): {}",
            output.status,
            err_text.trim()
        ));
    }
    Ok(info)
}

fn parse(stdout: &str, stderr: &str) -> GdbInfo {
    let mut info = GdbInfo {
        executable: None,
        command_line: None,
        signal: None,
        signal_name: None,
        frames: Vec::new(),
    };

    for line in stderr.lines().chain(stdout.lines()) {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("Core was generated by `") {
            if let Some(end) = rest.rfind('\'') {
                let cmdline = &rest[..end];
                info.command_line = Some(cmdline.to_string());
                let exe = cmdline.split_whitespace().next().unwrap_or("").to_string();
                if !exe.is_empty() {
                    info.executable = Some(exe);
                }
            }
        }
        // "Program terminated with signal SIGSEGV, Segmentation fault."
        if let Some(rest) = line.strip_prefix("Program terminated with signal ") {
            let name = rest.split(',').next().unwrap_or("").trim().to_string();
            if !name.is_empty() {
                info.signal_name = Some(name.clone());
                info.signal = signal_number(&name);
            }
        }
    }

    let shlibs = parse_shlibs(stdout);

    for line in stdout.lines() {
        if let Some(mut frame) = parse_frame(line.trim_start()) {
            // gdb sometimes prints the innermost frame twice (once when it
            // loads the core, once as `bt`'s row 0). Skip a repeat of the
            // last-seen index with the same address.
            if let Some(prev) = info.frames.last() {
                if prev.index == frame.index && prev.address == frame.address {
                    continue;
                }
            }
            // If `bt` didn't tell us the loaded object (it only does for
            // symbolless "from /lib/foo" frames), try to attribute the frame's
            // address to one of the mapped shared libraries. Frames whose
            // address falls outside every shlib range are in the executable
            // itself, which the caller fills in.
            if frame.binary.is_none() {
                if let Some(addr) = frame.address.as_deref().and_then(parse_hex_addr) {
                    if let Some(sh) = shlibs.iter().find(|s| addr >= s.from && addr < s.to) {
                        frame.binary = Some(sh.path.clone());
                    }
                }
            }
            info.frames.push(frame);
        }
    }

    // gdb often omits the address on frame #0 (the innermost signal handler),
    // so we can't range-map it. Since #0 is always called from #1, and an
    // inlined frame lives in the same object as its caller, propagate the
    // caller's binary backward to any leading frame that has neither address
    // nor binary of its own.
    for i in 0..info.frames.len() {
        if info.frames[i].binary.is_some() || info.frames[i].address.is_some() {
            continue;
        }
        if let Some(next_binary) = info.frames.get(i + 1).and_then(|f| f.binary.clone()) {
            info.frames[i].binary = Some(next_binary);
        }
    }
    info
}

/// Parse the `info sharedlibrary` table. gdb prints a header line and one row
/// per mapped shared object:
///
///   From                To                  Syms Read   Shared Object Library
///   0x00007ffff7d94000  0x00007ffff7f8a000  Yes         /usr/lib/x86_64-linux-gnu/libc.so.6
///
/// We only accept rows while we're inside the table (bracketed by the header
/// and the next blank line) so that a `bt` line starting with `0x...` can
/// never be misread as a shlib row.
fn parse_shlibs(stdout: &str) -> Vec<Shlib> {
    let mut out = Vec::new();
    let mut in_table = false;
    for line in stdout.lines() {
        let trimmed = line.trim_start();
        if trimmed.starts_with("From")
            && trimmed.contains("To")
            && trimmed.contains("Shared Object")
        {
            in_table = true;
            continue;
        }
        if !in_table {
            continue;
        }
        if trimmed.is_empty() {
            in_table = false;
            continue;
        }
        let Some(rest) = trimmed.strip_prefix("0x") else {
            // A non-hex line inside the table means the table has ended (e.g.
            // gdb printed `(*): Shared library is missing debugging info.`).
            in_table = false;
            continue;
        };
        let mut it = rest.split_whitespace();
        let Some(from_hex) = it.next() else { continue };
        let Some(to_field) = it.next() else { continue };
        let to_hex = to_field.strip_prefix("0x").unwrap_or(to_field);
        // Skip the "Syms Read" column (Yes/No). gdb sometimes prefixes it with
        // "(*)" when symbols are missing -- either way it's one token.
        if it.next().is_none() {
            continue;
        }
        // Remaining tokens form the path (which never contains whitespace in
        // practice, but be lenient).
        let path: String = it.collect::<Vec<_>>().join(" ");
        if path.is_empty() {
            continue;
        }
        let (Ok(from), Ok(to)) = (
            u64::from_str_radix(from_hex, 16),
            u64::from_str_radix(to_hex, 16),
        ) else {
            continue;
        };
        out.push(Shlib { from, to, path });
    }
    out
}

fn parse_hex_addr(s: &str) -> Option<u64> {
    let s = s.strip_prefix("0x").unwrap_or(s);
    u64::from_str_radix(s, 16).ok()
}

/// Parse a single `bt` output line. gdb's format is fairly stable:
///   `#0  0x0000... in fn_name (args) at file:line`
///   `#1  fn_name (args) at file:line`
///   `#2  0x0000... in fn_name () from /usr/lib/libfoo.so.1`
///   `#3  0x0000... in ?? ()`
fn parse_frame(line: &str) -> Option<RawFrame> {
    let rest = line.strip_prefix('#')?;
    let (idx_str, rest) = rest.split_once(|c: char| c.is_whitespace())?;
    let index: u32 = idx_str.parse().ok()?;
    let rest = rest.trim_start();

    let (address, after_addr) = if let Some(after) = rest.strip_prefix("0x") {
        let end = after
            .find(|c: char| !c.is_ascii_hexdigit())
            .unwrap_or(after.len());
        let (hex, tail) = after.split_at(end);
        (Some(format!("0x{hex}")), tail.trim_start())
    } else {
        (None, rest)
    };

    let after_in = after_addr.strip_prefix("in ").unwrap_or(after_addr);
    // Function name: everything up to the first ` (` that begins the arg list.
    let (function, tail) = match after_in.find(" (") {
        Some(i) => (Some(after_in[..i].trim().to_string()), &after_in[i..]),
        None => (None, after_in),
    };

    let (file, line_no, binary) = parse_frame_tail(tail);

    // Skip pure noise lines (no address, no function, no file). gdb also emits
    // blank lines and headers we don't want.
    if address.is_none() && function.is_none() && file.is_none() {
        return None;
    }

    Some(RawFrame {
        index,
        address,
        function,
        file,
        line: line_no,
        binary,
    })
}

fn parse_frame_tail(tail: &str) -> (Option<String>, Option<u32>, Option<String>) {
    // Skip past the argument-list parens. gdb doesn't nest parens inside the
    // arg list when frame-arguments is off (it prints `()`), so a simple depth
    // counter is fine.
    let mut depth = 0i32;
    let mut end = 0usize;
    let bytes = tail.as_bytes();
    for (i, &b) in bytes.iter().enumerate() {
        match b {
            b'(' => depth += 1,
            b')' => {
                depth -= 1;
                if depth == 0 {
                    end = i + 1;
                    break;
                }
            }
            _ => {}
        }
    }
    let after_args = tail[end..].trim_start();
    if let Some(rest) = after_args.strip_prefix("at ") {
        let (file, line) = split_file_line(rest);
        (Some(file), line, None)
    } else if let Some(rest) = after_args.strip_prefix("from ") {
        (None, None, Some(rest.trim().to_string()))
    } else {
        (None, None, None)
    }
}

fn split_file_line(s: &str) -> (String, Option<u32>) {
    match s.rsplit_once(':') {
        Some((path, tail)) => {
            let digits: String = tail.chars().take_while(|c| c.is_ascii_digit()).collect();
            if digits.is_empty() {
                (s.to_string(), None)
            } else {
                (path.to_string(), digits.parse().ok())
            }
        }
        None => (s.to_string(), None),
    }
}

fn signal_number(name: &str) -> Option<i32> {
    match name {
        "SIGHUP" => Some(1),
        "SIGINT" => Some(2),
        "SIGQUIT" => Some(3),
        "SIGILL" => Some(4),
        "SIGTRAP" => Some(5),
        "SIGABRT" | "SIGIOT" => Some(6),
        "SIGBUS" => Some(7),
        "SIGFPE" => Some(8),
        "SIGKILL" => Some(9),
        "SIGSEGV" => Some(11),
        "SIGPIPE" => Some(13),
        "SIGALRM" => Some(14),
        "SIGTERM" => Some(15),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_typical_bt() {
        let sample = "\
Core was generated by `/usr/bin/foo --flag arg'.
Program terminated with signal SIGSEGV, Segmentation fault.
#0  0x00007f1234567890 in ?? ()
#1  0x00005555deadbeef in bar::baz () at src/bar.rs:42
#2  0x0000555500001234 in main () at src/main.rs:10
#3  0x00007f00abcd1234 in __libc_start_call_main () from /lib/x86_64-linux-gnu/libc.so.6
";
        let info = parse(sample, "");
        assert_eq!(info.executable.as_deref(), Some("/usr/bin/foo"));
        assert_eq!(
            info.command_line.as_deref(),
            Some("/usr/bin/foo --flag arg")
        );
        assert_eq!(info.signal, Some(11));
        assert_eq!(info.signal_name.as_deref(), Some("SIGSEGV"));
        assert_eq!(info.frames.len(), 4);
        assert_eq!(
            info.frames[0].address.as_deref(),
            Some("0x00007f1234567890")
        );
        assert_eq!(info.frames[1].function.as_deref(), Some("bar::baz"));
        assert_eq!(info.frames[1].file.as_deref(), Some("src/bar.rs"));
        assert_eq!(info.frames[1].line, Some(42));
        assert_eq!(info.frames[2].function.as_deref(), Some("main"));
        assert_eq!(
            info.frames[3].function.as_deref(),
            Some("__libc_start_call_main")
        );
        assert_eq!(
            info.frames[3].binary.as_deref(),
            Some("/lib/x86_64-linux-gnu/libc.so.6")
        );
    }

    #[test]
    fn shlib_ranges_attribute_symbolic_frames_to_their_loaded_object() {
        // A `bt` line that names a function ("in foo () at file:line") doesn't
        // tell us the loaded object, but the address falling inside a shlib
        // range does.
        let sample = "\
Core was generated by `/usr/bin/hello'.
From                To                  Syms Read   Shared Object Library
0x00007ffff7d94000  0x00007ffff7f8a000  Yes         /usr/lib/x86_64-linux-gnu/libc.so.6
0x00007ffff7fc6000  0x00007ffff7fff000  Yes         /lib64/ld-linux-x86-64.so.2
#0  __GI__exit (status=0) at ../sysdeps/unix/sysv/linux/_exit.c:30
#1  0x00007ffff7dd6ad6 in __run_exit_handlers () at ./stdlib/exit.c:141
#2  0x000055555555678d in main () at src/hello.c:168
";
        let info = parse(sample, "");
        assert_eq!(info.frames.len(), 3);
        // The libc frame's address was inside the libc range.
        assert_eq!(
            info.frames[1].binary.as_deref(),
            Some("/usr/lib/x86_64-linux-gnu/libc.so.6"),
        );
        // The main frame's address falls outside every shlib, so no
        // attribution is added (the caller will map it to the executable).
        assert_eq!(info.frames[2].binary, None);
        // Frame 0 has no address at all, so it's attributed to its caller's
        // loaded object (libc) via the propagation pass.
        assert_eq!(
            info.frames[0].binary.as_deref(),
            Some("/usr/lib/x86_64-linux-gnu/libc.so.6"),
        );
    }

    #[test]
    fn drops_duplicate_innermost_frame() {
        // gdb prints frame 0 both when loading the core and when running `bt`.
        let sample = "\
Core was generated by `./crash'.
Program terminated with signal SIGSEGV, Segmentation fault.
#0  0x0000558241236149 in deref_null () at crash.c:5
#0  0x0000558241236149 in deref_null () at crash.c:5
#1  0x000055824123616a in middle () at crash.c:10
";
        let info = parse(sample, "");
        assert_eq!(info.frames.len(), 2);
        assert_eq!(info.frames[0].function.as_deref(), Some("deref_null"));
        assert_eq!(info.frames[1].function.as_deref(), Some("middle"));
    }

    #[test]
    fn parses_frame_without_address() {
        let f = parse_frame("#5  handle_signal (sig=11) at signals.c:99").unwrap();
        assert_eq!(f.index, 5);
        assert_eq!(f.function.as_deref(), Some("handle_signal"));
        assert_eq!(f.file.as_deref(), Some("signals.c"));
        assert_eq!(f.line, Some(99));
    }

    #[test]
    fn parse_shlibs_only_reads_within_the_table() {
        // Rows preceded by the header are picked up; the row after the blank
        // line (imitating a raw `0x...` on some unrelated future gdb output)
        // must not be.
        let sample = "\
From                To                  Syms Read   Shared Object Library
0x00007ffff7d94000  0x00007ffff7f8a000  Yes         /usr/lib/x86_64-linux-gnu/libc.so.6

0x00007ffff9999000  0x00007ffff9ffe000  Yes         /should/not/be/picked/up.so
";
        let shlibs = parse_shlibs(sample);
        assert_eq!(shlibs.len(), 1);
        assert_eq!(shlibs[0].path, "/usr/lib/x86_64-linux-gnu/libc.so.6");
    }
}
